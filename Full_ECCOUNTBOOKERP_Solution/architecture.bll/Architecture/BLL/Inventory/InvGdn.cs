	public static int Save(Architecture.Model.Inventory.InvGdn obj)
	{
		try
		{
			if (obj.Id == 0)
			{
				if (obj.invGdnDetail.Exists((InvGdnDetail p) => p.Id > 0))
				{
					throw new Exception("Record cannot be inserted because detailId greater than zero");
				}
				obj.ModifyUser = 0;
				obj.ActionId = 1;
				return new Architecture.DAL.Inventory.InvGdn().SetData(obj, "Sp_InvGdn_Insert");
			}
			obj.EntryUser = 0;
			obj.ActionId = 2;
			return new Architecture.DAL.Inventory.InvGdn().SetData(obj, "Sp_InvGdn_Update");
		}
		catch (Exception ex)
		{
			throw new Exception(ex.Message);
		}
