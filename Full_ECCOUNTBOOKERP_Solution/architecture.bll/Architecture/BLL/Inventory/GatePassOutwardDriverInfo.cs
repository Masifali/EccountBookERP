	public static int Save(Architecture.Model.Inventory.GatePassOutwardDriverInfo obj)
	{
		try
		{
			DataTable dt = DateLock.GetByOrganizationCompanyIdAndDate(new Architecture.Model.DateLock
			{
				OrganizationId = obj.OrganizationId,
				CompanyId = obj.CompanyId
			});
			if (dt != null && (obj.GpDate == Conversion.ToDateTime(dt.Rows[0]["Date"]) || obj.GpDate < Conversion.ToDateTime(dt.Rows[0]["Date"])))
			{
				throw new Exception("Not Insert or Update record please check lock date");
			}
			obj.EntryDate = DateTime.Now;
			obj.ModifyDate = DateTime.Now;
			if (obj.Id == 0)
			{
				return new Architecture.DAL.Inventory.GatePassOutwardDriverInfo().SetData(obj, "Sp_GatePassOutwardDriverInfo_Insert");
			}
			return new Architecture.DAL.Inventory.GatePassOutwardDriverInfo().SetData(obj, "Sp_GatePassOutwardDriverInfo_Update");
		}
		catch (Exception ex)
		{
			throw new Exception(ex.Message);
		}
	}

