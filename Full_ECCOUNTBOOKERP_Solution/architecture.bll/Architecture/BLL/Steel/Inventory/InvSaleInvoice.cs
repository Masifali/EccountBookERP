	public static int Save(Architecture.Model.Steel.Inventory.InvSaleInvoice obj)
	{
		try
		{
			if (obj.Id == 0)
			{
				if (obj.InvSaleInvoiceDetaillist.Exists((Architecture.Model.Steel.Inventory.InvSaleInvoiceDetail p) => p.ActionTypeId != 1))
				{
					throw new Exception("Record cannot be inserted because ActionTypeId greater than 1");
				}
				obj.ActionId = 1;
				obj.VoucherHeadInvoices = SaleInvoiceFinancial.MakeVoucherForSaleInvoice(obj);
				return new Architecture.DAL.Steel.Inventory.InvSaleInvoice().SetData(obj, "ST.USP_InvSaleInvoice_Insert");
			}
			obj.ActionId = 2;
			obj.VoucherHeadInvoices = SaleInvoiceFinancial.MakeVoucherForSaleInvoice(obj);
			return new Architecture.DAL.Steel.Inventory.InvSaleInvoice().SetData(obj, "ST.USP_InvSaleInvoice_Update");
		}
		catch (Exception ex)
		{
			throw new Exception(ex.Message);
		}
	}

