	private void ComboFill()
	{
		try
		{
			DataTable StockParty = new DataTable();
			StockParty.Columns.Add("Id");
			StockParty.Columns.Add("name");
			DataTable RefParty = new DataTable();
			RefParty.Columns.Add("Id");
			RefParty.Columns.Add("name");
			DataTable dtitem = new DataTable();
			dtitem.Columns.Add("Id");
			dtitem.Columns.Add("name");
			DataTable dtwh = new DataTable();
			dtwh.Columns.Add("Id");
			dtwh.Columns.Add("name");
			DataTable dtjl = new DataTable();
			dtjl.Columns.Add("Id");
			dtjl.Columns.Add("name");
			dtBindCombo = InvGrnPartyProcessing.GetDataForDropDownFromGrn(UserAccount.OrganizationId, UserAccount.CompanyId, (string)null, (string)null);
			if (dtBindCombo.Rows.Count <= 0)
			{
				return;
			}
			for (int i = 0; i < dtBindCombo.Rows.Count; i++)
			{
				if (Conversion.ToString(dtBindCombo.Rows[i]["Activity"]) == "StockParty")
				{
					StockParty.Rows.Add(dtBindCombo.Rows[i]["Id"], dtBindCombo.Rows[i]["ReferenceName"]);
				}
				else if (Conversion.ToString(dtBindCombo.Rows[i]["Activity"]) == "ReferenceParty")
				{
					RefParty.Rows.Add(dtBindCombo.Rows[i]["Id"], dtBindCombo.Rows[i]["ReferenceName"]);
				}
				else if (Conversion.ToString(dtBindCombo.Rows[i]["Activity"]) == "Item")
				{
					dtitem.Rows.Add(dtBindCombo.Rows[i]["Id"], dtBindCombo.Rows[i]["ReferenceName"]);
				}
				else if (Conversion.ToString(dtBindCombo.Rows[i]["Activity"]) == "Warehouse")
				{
					dtwh.Rows.Add(dtBindCombo.Rows[i]["Id"], dtBindCombo.Rows[i]["ReferenceName"]);
				}
				else if (Conversion.ToString(dtBindCombo.Rows[i]["Activity"]) == "JobLot")
				{
					dtjl.Rows.Add(dtBindCombo.Rows[i]["Id"], dtBindCombo.Rows[i]["ReferenceName"]);
				}
			}
			if (StockParty.Rows.Count > 0)
			{
				DDL.BindDDL(StockParty, CmbSupplier, "Id", "name", "Stock Party", ZeroIndex: false);
			}
			if (RefParty.Rows.Count > 0)
			{
				DDL.BindDDL(RefParty, cmbRefParty, "Id", "name", "Reference Party", ZeroIndex: false);
			}
			if (dtitem.Rows.Count > 0)
			{
				DDL.BindDDL(dtitem, CmbItem, "Id", "name", "Item", ZeroIndex: false);
			}
			if (dtwh.Rows.Count > 0)
			{
				DDL.BindDDL(dtwh, CmbWarehouseName, "Id", "name", "WareHouse", ZeroIndex: false);
				((UltraGridBase)CmbWarehouseName).DisplayLayout.AutoFitStyle = (AutoFitStyle)1;
			}
			if (dtjl.Rows.Count > 0)
			{
				DDL.BindDDL(dtjl, CmbJobLotName, "Id", "name", "JobLot", ZeroIndex: false);
				((UltraGridBase)CmbJobLotName).DisplayLayout.AutoFitStyle = (AutoFitStyle)1;
			}
		}
		catch (Exception ex)
		{
			MessageBox.Show(ex.Message);
		}
	}

