				table.Columns.Add("DocDate", typeof(DateTime));
				table.Columns.Add("DocNo", typeof(int));
				table.Columns.Add("DepartmentNameFrom", typeof(string));
				table.Columns.Add("ToDepartmentName", typeof(string));
				table.Columns.Add("RequestedQty", typeof(double));
				table.Columns.Add("ItemName", typeof(string));
				table.Columns.Add("UOMCode", typeof(string));
				table.Columns.Add("ItemCondition", typeof(string));
				table.Columns.Add("AssetName", typeof(string));
				table.Columns.Add("EntryDate", typeof(DateTime));
				table.Columns.Add("EntryUser", typeof(string));
				table.Columns.Add("ModifyDate", typeof(DateTime));
				table.Columns.Add("ModifyUser", typeof(string));
				table.Columns.Add("NoOfAttachments", typeof(int));
				for (int i = 0; i < dt.Rows.Count; i++)
				{
					table.Rows.Add(Conversion.ToInt(dt.Rows[i]["Id"]), Conversion.ToInt(dt.Rows[i]["DocTypeId"]), dt.Rows[i]["DocDate"], Conversion.ToInt(dt.Rows[i]["DocNo"]), Conversion.ToString(dt.Rows[i]["DepartmentNameFrom"]), Conversion.ToString(dt.Rows[i]["ToDepartmentName"]), Conversion.ToDouble(dt.Rows[i]["RequestedQty"]), Conversion.ToString(dt.Rows[i]["ItemName"]), Conversion.ToString(dt.Rows[i]["UOMCode"]), Conversion.ToString(dt.Rows[i]["ItemCondition"]), Conversion.ToString(dt.Rows[i]["AssetName"]), dt.Rows[i]["EntryDate"], Conversion.ToString(dt.Rows[i]["EntryUser"]), dt.Rows[i]["ModifyDate"], Conversion.ToString(dt.Rows[i]["ModifyUser"]), Conversion.ToString(dt.Rows[i]["NoOfAttachments"]));
