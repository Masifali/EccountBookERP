package com.mst.reports.jasper;

import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.Date;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Objects;
import java.util.Set;
import java.util.regex.Pattern;

/**
 * Builds a JasperReports template (.jrxml text) for a desktop print whose .rpt layout could not be
 * read, from the rows its procedure actually returned.
 *
 * What is taken from the .rpt: the page orientation (from its preview picture) and the pictures
 * embedded in it (the company logo), both extracted by migration/rpt-to-jasper/extract_seeded_prints.py.
 * What is taken from the data: every column, typed by its values.
 *
 * Layout rule, the one every desktop slip and register follows:
 *   - a column with the SAME value on every row is document data (doc no, date, party, remarks)
 *     and goes to the header block as "Label : value";
 *   - a column that changes per row is line data and becomes a detail column; numeric line
 *     columns get a total.
 * With one row nothing varies, so the split falls back to column names (item/qty/rate/amount...).
 * Ids, flags and company columns are left out; the company block prints them once.
 */
public final class GeneratedPrintTemplate {

    private GeneratedPrintTemplate() { }

    public static final class Meta {
        public String name;            // report name for the jrxml
        public String title;           // printed title
        public boolean landscape;
        public String logoResource;    // classpath image or null
        public String source;          // .rpt name, for the comment
    }

    private static final Set<String> COMPANY = Set.of(
            "compcode", "compname", "compaddress", "compcountry", "compcontactperson", "compmobilea",
            "compmobileb", "compmobilec", "compemaila", "compemailb", "complogoimage", "companywebsite",
            "companyfaxno", "orgreportingremarks", "phoneno", "companyname", "companyaddress", "companylogo");

    private static final Pattern HIDDEN = Pattern.compile(
            "(?i)^(id|.*id|.*ids|organizationid|companyid|actionid|actiontypeid|isactive|entryuser|entrydate|"
            + "modifiedby|modifieddate|updatedby|updateddate|row_count|rownum|srno_hidden|decimal.*|.*decimals.*|"
            + "decimalsfor.*|.*image|.*logo.*|.*signature.*|documenttypesrno|basedocumenttypeid)$");

    private static final Pattern LINE_NAME = Pattern.compile(
            "(?i).*(item|product|qty|quantity|rate|amount|price|weight|wt|bag|bags|uom|unit|discount|tax|value|"
            + "description|particular|narration|debit|credit|balance|lot|crop|packing|kg|mound|maund|net|gross).*");

    /** @return jrxml text; fieldClasses gets each column's Java class so the caller can type the rows. */
    public static String build(Meta m, List<Map<String, Object>> rows, Map<String, Class<?>> fieldClasses) {
        // ---- columns, in procedure order, typed by their values
        LinkedHashSet<String> cols = new LinkedHashSet<>();
        for (Map<String, Object> r : rows) cols.addAll(r.keySet());
        Map<String, Class<?>> type = new LinkedHashMap<>();
        for (String c : cols) type.put(c, typeOf(rows, c));
        fieldClasses.putAll(type);

        List<String> header = new ArrayList<>(), detail = new ArrayList<>();
        for (String c : cols) {
            String lc = c.toLowerCase(Locale.ROOT);
            if (COMPANY.contains(lc) || HIDDEN.matcher(c).matches() || type.get(c) == byte[].class) continue;
            if (allEmpty(rows, c)) continue;
            boolean constant = rows.size() > 1 ? isConstant(rows, c) : !LINE_NAME.matcher(c).matches();
            (constant ? header : detail).add(c);
        }
        if (detail.isEmpty() && !header.isEmpty() && rows.size() > 1) { detail.addAll(header); header.clear(); }

        // ---- page geometry
        boolean land = m.landscape || detail.size() > 9;
        int pageW = land ? 842 : 595, pageH = land ? 595 : 842, margin = 20, W = pageW - 2 * margin;
        float fs = detail.size() > 14 ? 6f : detail.size() > 10 ? 6.5f : 7.5f;
        int maxCols = Math.max(1, W / 34);
        List<String> shown = detail.size() > maxCols ? detail.subList(0, maxCols) : detail;
        int hidden = detail.size() - shown.size();

        StringBuilder x = new StringBuilder();
        x.append("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- Generated by GeneratedPrintTemplate for ")
         .append(esc(m.source)).append(": orientation and logo from the .rpt, columns from its procedure. "
                + "Edit freely; a saved copy of this file is used instead of regenerating. -->\n");
        x.append("<jasperReport xmlns=\"http://jasperreports.sourceforge.net/jasperreports\" "
                + "xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\" "
                + "xsi:schemaLocation=\"http://jasperreports.sourceforge.net/jasperreports http://jasperreports.sourceforge.net/xsd/jasperreport.xsd\" ")
         .append("name=\"").append(esc(m.name)).append("\" pageWidth=\"").append(pageW).append("\" pageHeight=\"").append(pageH)
         .append(land ? "\" orientation=\"Landscape" : "").append("\" columnWidth=\"").append(W)
         .append("\" leftMargin=\"20\" rightMargin=\"20\" topMargin=\"20\" bottomMargin=\"20\" whenNoDataType=\"AllSectionsNoDetail\" isSummaryWithPageHeaderAndFooter=\"true\">\n");
        x.append("<property name=\"net.sf.jasperreports.awt.ignore.missing.font\" value=\"true\"/>\n");
        x.append("<import value=\"com.mst.reports.jasper.CR\"/>\n");
        x.append("<parameter name=\"CompanyName\" class=\"java.lang.String\" isForPrompting=\"false\"/>\n");
        x.append("<parameter name=\"CompanyAddress\" class=\"java.lang.String\" isForPrompting=\"false\"/>\n");
        x.append("<parameter name=\"PrintedBy\" class=\"java.lang.String\" isForPrompting=\"false\"/>\n");
        for (Map.Entry<String, Class<?>> e : type.entrySet()) {
            x.append("<field name=\"").append(esc(e.getKey())).append("\" class=\"")
             .append(e.getValue() == byte[].class ? "java.lang.Object" : e.getValue().getName()).append("\"/>\n");
        }
        for (String c : shown) {
            if (type.get(c) == BigDecimal.class) {
                x.append("<variable name=\"T_").append(safe(c)).append("\" class=\"java.math.BigDecimal\" calculation=\"Sum\">")
                 .append("<variableExpression>").append(cd("$F{" + c + "}")).append("</variableExpression></variable>\n");
            }
        }

        // ---- page header: company block + title + header fields + column heads
        StringBuilder ph = new StringBuilder();
        int y = 0;
        ph.append(rect(0, 0, W, 60, 1f, null));
        int tx = 6;
        if (m.logoResource != null) {
            ph.append("<image scaleImage=\"RetainShape\" hAlign=\"Left\" vAlign=\"Middle\" onErrorType=\"Blank\">")
              .append(re(4, 4, 80, 52)).append("<imageExpression>").append(cd("CR.resource(\"" + m.logoResource + "\")"))
              .append("</imageExpression></image>");
            tx = 90;
        }
        String logoCol = firstPresent(type.keySet(), "CompLogoImage");
        if (m.logoResource == null && logoCol != null) {
            ph.append("<image scaleImage=\"RetainShape\" hAlign=\"Left\" vAlign=\"Middle\" onErrorType=\"Blank\">")
              .append(re(4, 4, 80, 52)).append("<imageExpression>").append(cd("CR.img($F{" + logoCol + "})"))
              .append("</imageExpression></image>");
            tx = 90;
        }
        String compName = firstPresent(type.keySet(), "CompName");
        String compAddr = firstPresent(type.keySet(), "CompAddress");
        ph.append(text(tx, 4, W - tx - 4, 20, "CR.s($P{CompanyName}).isEmpty() ? " + (compName == null ? "\"\"" : "CR.s($F{" + compName + "})") + " : $P{CompanyName}",
                14f, true, "Left", null));
        ph.append(text(tx, 24, W - tx - 4, 14, "CR.s($P{CompanyAddress}).isEmpty() ? " + (compAddr == null ? "\"\"" : "CR.s($F{" + compAddr + "})") + " : $P{CompanyAddress}",
                8f, false, "Left", null));
        List<String> contact = new ArrayList<>();
        for (String c : new String[]{"CompMobileA", "CompEmailA", "CompanyWebsite"}) {
            String f = firstPresent(type.keySet(), c);
            if (f != null) contact.add("$F{" + f + "}");
        }
        if (!contact.isEmpty())
            ph.append(text(tx, 38, W - tx - 4, 13, "CR.joinNonEmpty(\"   \", " + String.join(", ", contact) + ")", 7.5f, false, "Left", null));
        y = 64;
        ph.append(rect(0, y, W, 18, 1f, null));
        ph.append(stat(0, y, W, 18, m.title, 12f, true, "Center", "#007F7F"));
        y += 22;

        if (!header.isEmpty()) {
            int perRow = land ? 3 : 2, cw = W / perRow, lw = Math.min(110, cw / 2 - 4), rowH = 13;
            for (int i = 0; i < header.size(); i++) {
                String c = header.get(i);
                int cx = (i % perRow) * cw, cy = y + (i / perRow) * rowH;
                ph.append(stat(cx + 2, cy, lw, rowH, label(c) + " :", 7.5f, true, "Left", null));
                ph.append(text(cx + 2 + lw, cy, cw - lw - 6, rowH, valueExpr(c, type.get(c)), 7.5f, false, "Left", null));
            }
            y += ((header.size() + perRow - 1) / perRow) * rowH + 4;
        }
        int[] widths = widths(shown, type, rows, W);
        if (!shown.isEmpty()) {
            int cx = 0;
            for (int i = 0; i < shown.size(); i++) {
                ph.append("<staticText>").append(re(cx, y, widths[i], 24, "#E6E6E6", null)).append(box(true))
                  .append(te(isNum(type.get(shown.get(i))) ? "Center" : "Center", fs, true))
                  .append("<text>").append(cd(label(shown.get(i)))).append("</text></staticText>");
                cx += widths[i];
            }
            y += 24;
        }
        x.append("<pageHeader><band height=\"").append(y).append("\" splitType=\"Stretch\">").append(ph).append("</band></pageHeader>\n");

        // ---- detail
        if (!shown.isEmpty()) {
            StringBuilder d = new StringBuilder();
            int cx = 0;
            for (int i = 0; i < shown.size(); i++) {
                String c = shown.get(i);
                d.append("<textField textAdjust=\"StretchHeight\" isBlankWhenNull=\"true\">")
                 .append(re(cx, 0, widths[i], 13, null, "ContainerHeight")).append(box(false))
                 .append(te(isNum(type.get(c)) ? "Right" : "Left", fs, false))
                 .append("<textFieldExpression>").append(cd(valueExpr(c, type.get(c)))).append("</textFieldExpression></textField>");
                cx += widths[i];
            }
            x.append("<detail><band height=\"13\" splitType=\"Stretch\">").append(d).append("</band></detail>\n");
        }

        // ---- page footer
        x.append("<pageFooter><band height=\"22\">")
         .append(rect(0, 2, W, 14, 0.75f, "#E6E6E6"))
         .append(text(2, 2, 250, 14, "\"Printed By : \" + CR.s($P{PrintedBy})", 7f, false, "Left", null))
         .append(text(250, 2, 200, 14, "\"Print Date : \" + CR.dt(new java.util.Date(), \"dd/MM/yyyy hh:mm a\")", 7f, false, "Left", null))
         .append(text(W - 120, 2, 80, 14, "\"Page \" + $V{PAGE_NUMBER} + \" of\"", 7f, false, "Right", null))
         .append("<textField evaluationTime=\"Report\">").append(re(W - 40, 2, 38, 14)).append(te("Left", 7f, false))
         .append("<textFieldExpression>").append(cd("\" \" + $V{PAGE_NUMBER}")).append("</textFieldExpression></textField>")
         .append(rect(0, 17, W, 4, 0f, "#007F7F"))
         .append("</band></pageFooter>\n");

        // ---- summary: totals of the numeric line columns
        StringBuilder s = new StringBuilder();
        boolean anyTotal = false;
        int cx = 0;
        for (int i = 0; i < shown.size(); i++) {
            String c = shown.get(i);
            if (type.get(c) == BigDecimal.class && !isRateLike(c)) {
                anyTotal = true;
                s.append("<textField isBlankWhenNull=\"true\">").append(re(cx, 2, widths[i], 14)).append(box(true))
                 .append(te("Right", fs, true)).append("<textFieldExpression>")
                 .append(cd("CR.amt($V{T_" + safe(c) + "}, " + decimalsFor(c) + ", false)"))
                 .append("</textFieldExpression></textField>");
            }
            cx += widths[i];
        }
        if (anyTotal) s.insert(0, stat(0, 2, widths.length > 0 ? widths[0] : 60, 14, "Total", fs, true, "Left", null));
        if (hidden > 0) {
            s.append(text(0, anyTotal ? 18 : 2, W, 12, "\"" + hidden + " further column(s) returned by the procedure do not fit the page: "
                    + esc(String.join(", ", detail.subList(shown.size(), detail.size()))).replace("\"", "'") + "\"", 6f, false, "Left", null));
        }
        if (s.length() > 0) x.append("<summary><band height=\"").append(hidden > 0 ? 32 : 18).append("\">").append(s).append("</band></summary>\n");
        x.append("</jasperReport>\n");
        return x.toString();
    }

    // ------------------------------------------------------------------ helpers
    static Class<?> typeOf(List<Map<String, Object>> rows, String c) {
        for (Map<String, Object> r : rows) {
            Object v = r.get(c);
            if (v == null) continue;
            if (v instanceof byte[]) return byte[].class;
            if (v instanceof Boolean) return Boolean.class;
            if (v instanceof Number) return BigDecimal.class;
            if (v instanceof Date || v instanceof java.time.temporal.Temporal) return Date.class;
            return String.class;
        }
        return String.class;
    }

    static boolean isConstant(List<Map<String, Object>> rows, String c) {
        Object first = rows.get(0).get(c);
        for (Map<String, Object> r : rows) if (!Objects.equals(first, r.get(c))) return false;
        return true;
    }

    static boolean allEmpty(List<Map<String, Object>> rows, String c) {
        for (Map<String, Object> r : rows) {
            Object v = r.get(c);
            if (v != null && !String.valueOf(v).trim().isEmpty()) return false;
        }
        return true;
    }

    static boolean isNum(Class<?> c) { return c == BigDecimal.class; }

    static boolean isRateLike(String c) { return c.toLowerCase(Locale.ROOT).matches(".*(rate|price|percent|pct|%|days|no|srno|code).*"); }

    static String decimalsFor(String c) {
        String l = c.toLowerCase(Locale.ROOT);
        return l.matches(".*(qty|quantity|bags|bag|count|nos).*") ? "0" : "2";
    }

    static String valueExpr(String c, Class<?> t) {
        String f = "$F{" + c + "}";
        if (t == BigDecimal.class) return isRateLike(c) && !c.toLowerCase(Locale.ROOT).matches(".*(rate|price).*")
                ? "CR.s(" + f + ")" : "CR.amt(" + f + ", " + decimalsFor(c) + ", false)";
        if (t == Date.class) return "CR.dt(" + f + ", CR.hasTime(" + f + ") ? \"dd/MM/yyyy hh:mm a\" : \"dd/MM/yyyy\")";
        if (t == Boolean.class) return "CR.bool(" + f + ") ? \"Yes\" : \"No\"";
        return "CR.s(" + f + ")";
    }

    static int[] widths(List<String> cols, Map<String, Class<?>> type, List<Map<String, Object>> rows, int W) {
        int n = cols.size();
        int[] w = new int[n];
        if (n == 0) return w;
        double[] want = new double[n];
        double sum = 0;
        for (int i = 0; i < n; i++) {
            String c = cols.get(i);
            int maxLen = label(c).length();
            for (Map<String, Object> r : rows) {
                Object v = r.get(c);
                if (v != null) maxLen = Math.max(maxLen, Math.min(40, String.valueOf(v).length()));
            }
            want[i] = Math.max(isNum(type.get(c)) ? 9 : 6, maxLen);
            sum += want[i];
        }
        int used = 0;
        for (int i = 0; i < n; i++) { w[i] = (int) Math.floor(W * want[i] / sum); used += w[i]; }
        w[n - 1] += W - used;
        return w;
    }

    /** "SupplierCustomerName" -> "Supplier Customer Name". */
    public static String label(String c) {
        String s = c.replace('_', ' ').replaceAll("([a-z0-9])([A-Z])", "$1 $2").replaceAll("([A-Z]+)([A-Z][a-z])", "$1 $2").trim();
        return s.isEmpty() ? c : Character.toUpperCase(s.charAt(0)) + s.substring(1);
    }

    /** "273-InvRptSaleOrderSlip.rpt" -> "Sale Order Slip". */
    public static String titleOf(String template) {
        String s = template.replaceAll("(?i)\\.rpt$", "").replaceAll("^[0-9A-Za-z]{0,6}?[0-9]+[A-Za-z]?[-_ ]+(?:[0-9]+[-_ ]+)?", "")
                .replaceAll("(?i)^(Inv|Ac|Acc|Hr|Pr|Prd)?Rpt", "").replace('_', ' ').replace('-', ' ');
        s = label(s.replace(" ", ""));
        return s.isEmpty() ? template : s;
    }

    private static String firstPresent(Set<String> cols, String name) {
        for (String c : cols) if (c.equalsIgnoreCase(name)) return c;
        return null;
    }

    static String safe(String c) { return c.replaceAll("[^A-Za-z0-9_]", "_"); }

    static String esc(String s) {
        return s == null ? "" : s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;");
    }

    static String cd(String s) { return "<![CDATA[" + s.replace("]]>", "]]]]><![CDATA[>") + "]]>"; }

    static String re(int x, int y, int w, int h) { return re(x, y, w, h, null, null); }

    static String re(int x, int y, int w, int h, String bg, String stretch) {
        return "<reportElement x=\"" + x + "\" y=\"" + y + "\" width=\"" + Math.max(1, w) + "\" height=\"" + Math.max(1, h) + "\""
                + (bg != null ? " mode=\"Opaque\" backcolor=\"" + bg + "\"" : "")
                + (stretch != null ? " stretchType=\"" + stretch + "\"" : "") + "/>";
    }

    static String box(boolean all) {
        return all ? "<box><pen lineWidth=\"0.5\"/></box>"
                   : "<box><leftPen lineWidth=\"0.5\"/><bottomPen lineWidth=\"0.25\" lineColor=\"#BFBFBF\"/><rightPen lineWidth=\"0.5\"/></box>";
    }

    static String te(String align, float size, boolean bold) {
        return "<textElement textAlignment=\"" + align + "\" verticalAlignment=\"Middle\"><font fontName=\"Arial\" size=\""
                + size + "\"" + (bold ? " isBold=\"true\"" : "") + "/><paragraph leftIndent=\"2\" rightIndent=\"2\"/></textElement>";
    }

    static String text(int x, int y, int w, int h, String expr, float size, boolean bold, String align, String color) {
        String r = re(x, y, w, h);
        if (color != null) r = r.replace("/>", " forecolor=\"" + color + "\"/>");
        return "<textField textAdjust=\"StretchHeight\" isBlankWhenNull=\"true\">" + r + te(align, size, bold)
                + "<textFieldExpression>" + cd(expr) + "</textFieldExpression></textField>";
    }

    static String stat(int x, int y, int w, int h, String s, float size, boolean bold, String align, String color) {
        String r = re(x, y, w, h);
        if (color != null) r = r.replace("/>", " forecolor=\"" + color + "\"/>");
        return "<staticText>" + r + te(align, size, bold) + "<text>" + cd(s) + "</text></staticText>";
    }

    static String rect(int x, int y, int w, int h, float pen, String fill) {
        String r = re(x, y, w, h, fill, null);
        if (fill == null) r = r.replace("/>", " mode=\"Transparent\"/>");
        return "<rectangle>" + r + "<graphicElement><pen lineWidth=\"" + pen + "\"/></graphicElement></rectangle>";
    }
}
