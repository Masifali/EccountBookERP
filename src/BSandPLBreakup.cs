	private void btnshow_Click(object sender, EventArgs e)
	{
		try
		{
			if (dtvoucher.Rows.Count > 0)
			{
				DataTable dtGrid = new DataTable();
				dtGrid.Columns.Add("Id");
				dtGrid.Columns.Add("AccountCode");
				dtGrid.Columns.Add("AccountTitle");
				dtGrid.Columns.Add("AccountNoteId");
				dtGrid.Columns.Add("AccountNotes");
				dtGrid.Columns.Add("Amount", typeof(double));
				for (int i = 0; i < dtvoucher.Rows.Count; i++)
				{
					if (Conversion.ToInt(dtvoucher.Rows[i]["AccountNoteId"]) == NoteId)
					{
						dtGrid.Rows.Add(dtvoucher.Rows[i]["Id"], dtvoucher.Rows[i]["ParentAccountCode"], dtvoucher.Rows[i]["AccountTitle"], dtvoucher.Rows[i]["AccountNoteId"], dtvoucher.Rows[i]["AccountsNotes"], dtvoucher.Rows[i]["Amount"]);
					}
				}
				grd.DataSource = dtGrid;
				grd.RetrieveStructure();
				GridSettings();
			}
			else
			{
				grd.ClearStructure();
			}
		}
		catch (Exception ex)
		{
			MessageBox.Show(ex.Message);
		}
	}

