				dtHistory.Columns.Add("Warehouse", typeof(string));
				dtHistory.Columns.Add("JobLot", typeof(string));
				dtHistory.Columns.Add("ItemName", typeof(string));
				dtHistory.Columns.Add("PackUOM", typeof(string));
				dtHistory.Columns.Add("DoQty", typeof(double));
				dtHistory.Columns.Add("DoWeight", typeof(double));
				dtHistory.Columns.Add("LoadingQty", typeof(double));
				dtHistory.Columns.Add("LoadingWeight", typeof(double));
				dtHistory.Columns.Add("LoadingRemarks", typeof(string));
				dtHistory.Columns.Add("EntryUser", typeof(string));
				dtHistory.Columns.Add("EntryDate", typeof(DateTime));
				dtHistory.Columns.Add("ModifyUser", typeof(string));
				dtHistory.Columns.Add("ModifyDate", typeof(DateTime));
				dtHistory.Columns.Add("IsApproved", typeof(string));
				dtHistory.Columns.Add("NoOfAttachments", typeof(int));
				dtHistory.Clear();
				for (int i = 0; i < dtGrid.Rows.Count; i++)
				{
					dtHistory.Rows.Add(dtGrid.Rows[i]["Id"], dtGrid.Rows[i]["DocumentTypeId"], dtGrid.Rows[i]["DocNo"], Conversion.ToDateTime(dtGrid.Rows[i]["DocDate"]).ToShortDateString(), dtGrid.Rows[i]["DeliveryOrderType"], dtGrid.Rows[i]["SaleOrderId"], dtGrid.Rows[i]["SaleOrderNo"], dtGrid.Rows[i]["CustomerName"], dtGrid.Rows[i]["WareHouseName"], dtGrid.Rows[i]["JobLotDescription"], dtGrid.Rows[i]["ItemName"], dtGrid.Rows[i]["PackUOM"], dtGrid.Rows[i]["DoQty"], dtGrid.Rows[i]["DoWeight"], dtGrid.Rows[i]["LoadingQty"], dtGrid.Rows[i]["LoadingWeight"], dtGrid.Rows[i]["LoadingRemarks"], dtGrid.Rows[i]["EntryUserName"], dtGrid.Rows[i]["EntryDate"], dtGrid.Rows[i]["ModifyUserName"], Conversion.ToDateTime(dtGrid.Rows[i]["ModifyDate"]).ToShortDateString(), dtGrid.Rows[i]["IsApproved"], dtGrid.Rows[i]["NoOfAttachments"]);
				}
				grdHistory.DataSource = dtHistory;
				grdHistory.RetrieveStructure();
				GridSetting();
			}
			else
			{
				grdHistory.ClearStructure();
			}
