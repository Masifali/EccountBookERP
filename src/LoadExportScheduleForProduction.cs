	private void GridDataBind()
	{
		try
		{
			if (dtFromDb.Rows.Count > 0)
			{
				DataTable dataTable = dtGrid;
				if (dataTable != null && dataTable.Columns.Count == 0)
				{
					dtGrid.Columns.Add("Id", typeof(int));
					dtGrid.Columns.Add("ContractId", typeof(int));
					dtGrid.Columns.Add("ContractNo", typeof(string));
					dtGrid.Columns.Add("ScheduleNo", typeof(string));
					dtGrid.Columns.Add("SupplierCustomerId", typeof(int));
					dtGrid.Columns.Add("CustomerName", typeof(string));
					dtGrid.Columns.Add("CustomerContractNo", typeof(string));
					dtGrid.Columns.Add("LoadingDate", typeof(DateTime));
					dtGrid.Columns.Add("ProductionDate", typeof(DateTime));
					dtGrid.Columns.Add("ItemId", typeof(int));
					dtGrid.Columns.Add("ItemName", typeof(string));
					dtGrid.Columns.Add("MTon", typeof(double));
				}
				dtGrid.Rows.Clear();
				foreach (DataRow row in dtFromDb.Rows)
				{
					dtGrid.Rows.Add(row["Id"], row["ContractId"], row["ContractNo"], row["ScheduleCode"], row["SupplierCustomerId"], row["PartyName"], row["CustomerContractNo"], row["AttentiveLoadingDate"], row["AttentiveProductionDate"], row["ItemId"], row["ItemName"], row["MTon"]);
				}
				grd.DataSource = dtGrid;
				grd.RetrieveStructure();
				grdSettings();
			}
			else
			{
				grd.DataSource = null;
			}
		}
		catch (Exception ex)
		{
			MessageBox.Show(ex.Message);
		}
	}

