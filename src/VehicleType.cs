	public void BindGrid()
	{
		try
		{
			DataTable dtvehicle = VehicleType.GetAll();
			if (dtvehicle.Rows.Count > 0)
			{
				DataTable dt = new DataTable();
				dt.Columns.Add("Id", typeof(int));
				dt.Columns.Add("VehicleType", typeof(string));
				dt.Clear();
				for (int i = 0; i < dtvehicle.Rows.Count; i++)
				{
					dt.Rows.Add(dtvehicle.Rows[i]["Id"], dtvehicle.Rows[i]["VehicleDescription"]);
				}
				grdfrm.DataSource = dt;
				grdfrm.RetrieveStructure();
				grdfrm.RootTable.Columns["Id"].Visible = false;
				CommonServices.GridAutoAdjustmentNew(grdfrm);
			}
		}
		catch (Exception ex)
		{
			MessageBox.Show(ex.Message);
		}
	}

