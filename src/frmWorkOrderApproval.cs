	private void HistoryComboBind(DataTable dt)
	{
		try
		{
			DataTable dtCust = new DataTable();
			dtCust.Columns.Add("Id", typeof(int));
			dtCust.Columns.Add("Name", typeof(string));
			DataTable dtProductiontype = dtCust.Clone();
			DataTable dtBom = dtCust.Clone();
			DataTable dtItem = dtCust.Clone();
			DataTable dtPlant = dtCust.Clone();
			foreach (DataRow dr in dt.Rows)
			{
				switch (Conversion.ToString(dr["Activity"]))
				{
				case "Customer":
					dtCust.Rows.Add(dr["Id"], dr["ReferenceName"]);
					break;
				case "ProductionType":
					dtProductiontype.Rows.Add(dr["Id"], dr["ReferenceName"]);
					break;
				case "BomName":
					dtBom.Rows.Add(dr["Id"], dr["ReferenceName"]);
					break;
				case "Item":
					dtItem.Rows.Add(dr["Id"], dr["ReferenceName"]);
					break;
				case "Plant":
					dtPlant.Rows.Add(dr["Id"], dr["ReferenceName"]);
					break;
				}
			}
			InfragisticsHelper.BindAndRetainSelection(CmbProductionType, dtProductiontype, "Id", "Name", "Production Type", AllColumns: true, Conversion.ToInt(CmbProductionType.Value), insertDefaultRow: false, null, null, ActivateRow: false);
