	private void GetByMonthandYearForUpdate()
	{
		//IL_00ad: Unknown result type (might be due to invalid IL or missing references)
		try
		{
			int Month = Conversion.ToInt(cmbMonth.Value);
			int Year = Conversion.ToInt(cmbYear.Value);
			if (Month <= 0 || Year <= 0)
			{
				return;
			}
			List<genHoliday> lst = new List<genHoliday>();
			lst = genHoliday.GetByMonthAndYear(Month, Year);
			if (lst.Count <= 0)
			{
				return;
			}
			for (int i = 0; i < lst.Count; i++)
			{
				GridEXRow[] rows = grd.GetRows();
				foreach (GridEXRow r in rows)
				{
					if (Conversion.ToDateTime(r.Cells["Date"].Value) == lst[i].HolidayDate)
					{
						int rownumber = r.RowIndex;
						if (r != null && (int)r.RowType == 0)
						{
							r.Delete();
						}
						dtdate.Rows.Add(lst[i].HolidayId, rownumber, lst[i].HolidayDate.ToString("dd-MMM-yyyy"), lst[i].Name, lst[i].IsOffDay, lst[i].IsGazetted, lst[i].HolidayDetail);
					}
				}
			}
			grd.DataSource = dtdate;
			grd.RetrieveStructure();
			grdSetting();
		}
		catch (Exception ex)
		{
			MessageBox.Show(ex.Message);
		}
	}

	private void GenerateDatesOfMonth(int year, int month)
	{
		try
		{
			if (((UltraGridBase)cmbYear).ActiveRow != null || ((UltraGridBase)cmbMonth).ActiveRow != null)
			{
				dtdate.Rows.Clear();
				int GenerateSrNo = 1;
				new List<DateTime>();
				DateTime date = new DateTime(year, month, 1);
				while (date.Month == month)
				{
					dtdate.Rows.Add(0, GenerateSrNo++, date.ToString("dd-MMM-yyyy"), date.DayOfWeek, 0, 0, "");
					date = date.AddDays(1.0);
				}
				grd.DataSource = dtdate;
				grd.RetrieveStructure();
				grdSetting();
			}
			else
			{
				grd.ClearStructure();
				dtdate.Rows.Clear();
			}
		}
		catch (Exception ex)
		{
			MessageBox.Show(ex.Message);
		}
	}

	private void Insert()
	{
		//IL_0000: Unknown result type (might be due to invalid IL or missing references)
		//IL_0006: Expected O, but got Unknown
		//IL_00a9: Unknown result type (might be due to invalid IL or missing references)
		//IL_00b0: Expected O, but got Unknown
		try
		{
			genHoliday obj = new genHoliday();
			if (MessageBox.Show("Are you sure to Save?", "Confirm", MessageBoxButtons.YesNo, MessageBoxIcon.Question) == DialogResult.No)
			{
				return;
			}
			GridEXRow[] rows = grd.GetRows();
			foreach (GridEXRow r2 in rows)
			{
				if (Conversion.ToBool(r2.Cells["IsOff"].Value) && Conversion.ToBool(r2.Cells["IsGazette"].Value))
				{
					MessageBox.Show("On a Same Day you cannot check both IsOff and IsGazette");
					return;
				}
			}
			obj.genHolidaysList = new List<genHoliday>();
			rows = grd.GetRows();
			foreach (GridEXRow r in rows)
			{
				genHoliday holiday = new genHoliday();
				holiday.HolidayId = Conversion.ToInt(r.Cells["Id"].Value);
				holiday.HolidayDate = Conversion.ToDateTime(r.Cells["Date"].Value);
				holiday.HolidayDetail = Conversion.ToString((object)r.Cells["Description"].Text);
				holiday.Name = Conversion.ToString((object)r.Cells["Day"].Text);
				holiday.IsOffDay = Conversion.ToBool(r.Cells["IsOff"].Value);
				holiday.IsGazetted = Conversion.ToBool(r.Cells["IsGazette"].Value);
				holiday.UserLogId = UserAccount.ID;
				holiday.OrginizationId = UserAccount.OrganizationId;
				holiday.CompanyId = UserAccount.CompanyId;
				holiday.AlteredById = UserAccount.ID;
				holiday.CreatedById = UserAccount.ID;
				holiday.CreatedOn = DateTime.Now;
				holiday.AlteredOn = DateTime.Now;
				holiday.ActionTypeId = 1;
				obj.genHolidaysList.Add(holiday);
			}
			genHoliday.Save(obj);
			MessageBox.Show("Save Successfully");
			Reset();
		}
		catch (Exception ex)
		{
			MessageBox.Show(ex.Message);
		}
	}

