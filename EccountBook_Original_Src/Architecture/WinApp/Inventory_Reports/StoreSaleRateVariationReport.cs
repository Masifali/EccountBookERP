			obj.ItemId = Conversion.ToInt(CmbItem.Value);
			obj.SupplierCustomerId = Conversion.ToInt(cmbSuppplierName.Value);
			if (RadApproved.Checked)
			{
				obj.IsApproved = true;
			}
			if (RadNotApproved.Checked)
			{
				obj.IsApproved = false;
			}
			if (RadAll.Checked)
			{
				obj.ApprovedFilter = "All";
			}
			dtGridFromDb = InvPurchaseDemandHeader.StoreSaleRateVariation(obj);
		}
		catch (Exception ex)
		{
			MessageBox.Show(ex.Message);
		}
	}

	private void GridFill()
	{
		try
		{
			if (dtGridFromDb.Rows.Count > 0)
			{
				if (dtGrid.Columns.Count == 0)
				{
					dtGrid.Columns.Add("ItemId", typeof(int));
					dtGrid.Columns.Add("ItemCode", typeof(string));
					dtGrid.Columns.Add("ItemName", typeof(string));
					dtGrid.Columns.Add("SrNo", typeof(int));
					dtGrid.Columns.Add("ItemRate", typeof(decimal));
					dtGrid.Columns.Add("ItemQty", typeof(decimal));
					dtGrid.Columns.Add("SupplierCustomerId", typeof(int));
					dtGrid.Columns.Add("CustomerName", typeof(string));
					dtGrid.Columns.Add("SaleDate", typeof(DateTime));
					dtGrid.Columns.Add("MinRate", typeof(decimal));
					dtGrid.Columns.Add("MaxRate", typeof(decimal));
					dtGrid.Columns.Add("RateVariationPercent", typeof(decimal));
				}
				dtGrid.Clear();
				foreach (DataRow row in dtGridFromDb.Rows)
				{
					dtGrid.Rows.Add(row["ItemId"], row["ItemCode"], row["ItemName"], row["SrNo"], row["ItemRate"], row["ItemQty"], row["SupplierCustomerId"], row["CustomerName"], row["SaleDate"], row["MinRate"], row["MaxRate"], row["RateVariationPercent"]);
				}
				grdRateVariation.DataSource = dtGrid;
				grdRateVariation.RetrieveStructure();
				GridSettings();
			}
			else
			{
				grdRateVariation.DataSource = null;
			}
		}
		catch (Exception ex)
		{
			MessageBox.Show(ex.Message);
		}
	}

