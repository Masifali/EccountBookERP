	private void CombosFill(DataTable dtcombo)
	{
		try
		{
			DataTable dtCus = new DataTable();
			dtCus.Columns.Add("Id", typeof(int));
			dtCus.Columns.Add("Name");
			DataTable dtSP = dtCus.Clone();
			DataTable dtInv = dtCus.Clone();
			if (dtcombo.Rows.Count <= 0)
			{
				return;
			}
			for (int i = 0; i < dtcombo.Rows.Count; i++)
			{
				if (Conversion.ToString(dtcombo.Rows[i]["Activity"]) == "CustomerName")
				{
					dtCus.Rows.Add(dtcombo.Rows[i]["Id"], dtcombo.Rows[i]["ReferenceName"]);
				}
				else if (Conversion.ToString(dtcombo.Rows[i]["Activity"]) == "Transporter")
				{
					dtSP.Rows.Add(dtcombo.Rows[i]["Id"], dtcombo.Rows[i]["ReferenceName"]);
				}
				else if (Conversion.ToString(dtcombo.Rows[i]["Activity"]) == "ExportInvoiceNo")
				{
					dtInv.Rows.Add(dtcombo.Rows[i]["Id"], dtcombo.Rows[i]["ReferenceName"]);
				}
			}
			InfragisticsHelper.BindAndRetainSelection(CmbInvoiceNo, dtInv, "Id", "Name", "Invoice No", AllColumns: true, Conversion.ToInt(CmbInvoiceNo.Value), insertDefaultRow: true, null, null, ActivateRow: false);
			InfragisticsHelper.BindAndRetainSelection(CmbCustomer, dtCus, "Id", "Name", "Customer Name", AllColumns: true, Conversion.ToInt(CmbCustomer.Value), insertDefaultRow: true, null, null, ActivateRow: false);
