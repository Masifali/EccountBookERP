	private void btnLoadOnInvoice_Click_1(object sender, EventArgs e)
	{
		try
		{
			GridEXRow[] checkedRows = grd.GetCheckedRows();
			if (checkedRows.Count() == 0)
			{
				MessageBox.Show("Check the row first");
				return;
			}
			dtLoader = dtHistory.Clone();
			int baseId = Conversion.ToInt(checkedRows[0].Cells["ExImInvoiceId"].Value);
			List<int> detailIds = new List<int>();
			GridEXRow[] array = checkedRows;
			foreach (GridEXRow row in array)
			{
				if (Conversion.ToInt(row.Cells["ExImInvoiceId"].Value) != baseId)
				{
					MessageBox.Show("Sorry! You can Only Check rows which have the same Gp");
					return;
				}
				int ServicesBillHeaderId = Conversion.ToInt(row.Cells["ServicesBillHeaderId"].Value);
				int ServiceBillNo = Conversion.ToInt(row.Cells["ServiceBillNo"].Value);
				int DocNo = Conversion.ToInt(row.Cells["DocNo"].Value);
				int detailId = Conversion.ToInt(row.Cells["Id"].Value);
				if (ServicesBillHeaderId > 0 && !FreightVoucherIds.Any() && !FreightVoucherIds.Contains(detailId))
				{
					MessageBox.Show($"Sorry! You cannot load row with DocNo {DocNo}.\n" + $"It already exists against another ServicesBill {ServiceBillNo}.", "Validation Error", MessageBoxButtons.OK, MessageBoxIcon.Exclamation);
					return;
				}
				detailIds.Add(detailId);
			}
			if (detailIds.Count > 0)
			{
				List<DataRow> rows = (from r in dtHistory.AsEnumerable()
					where detailIds.Contains(r.Field<int>("Id"))
					select r).ToList();
				if (rows.Any())
				{
					dtLoader = rows.CopyToDataTable();
				}
			}
			Hide();
		}
		catch (Exception ex)
		{
			MessageBox.Show(ex.Message);
		}
	}

