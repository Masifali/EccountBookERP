	private void AllComboBind()
	{
		try
		{
			DataTable dt = ExImClearingAgentBill.GetDataForDropDownFromClearingAgentBill(UserAccount.OrganizationId, UserAccount.CompanyId, (string)null);
			if (dt.Rows.Count <= 0)
			{
				return;
			}
			DataTable dtInvoice = new DataTable();
			dtInvoice.Columns.Add("Id");
			dtInvoice.Columns.Add("Invoice");
			DataTable dtCustomer = new DataTable();
			dtCustomer.Columns.Add("Id");
			dtCustomer.Columns.Add("CustomerName");
			DataTable dtLoadingPort = new DataTable();
			dtLoadingPort.Columns.Add("Id");
			dtLoadingPort.Columns.Add("Port");
			DataTable dtItem = new DataTable();
			dtItem.Columns.Add("Id");
			dtItem.Columns.Add("ItemName");
			DataTable dtDestinationPort = new DataTable();
			dtDestinationPort.Columns.Add("Id");
			dtDestinationPort.Columns.Add("Port");
			for (int i = 0; i < dt.Rows.Count; i++)
			{
				if (Conversion.ToString(dt.Rows[i]["ActivityType"]) == "Customer")
				{
					dtCustomer.Rows.Add(dt.Rows[i]["Id"], dt.Rows[i]["name"]);
				}
				else if (Conversion.ToString(dt.Rows[i]["ActivityType"]) == "Invoice")
				{
					dtInvoice.Rows.Add(dt.Rows[i]["Id"], dt.Rows[i]["name"]);
				}
				else if (Conversion.ToString(dt.Rows[i]["ActivityType"]) == "LoadingPort")
				{
					dtLoadingPort.Rows.Add(dt.Rows[i]["Id"], dt.Rows[i]["name"]);
				}
				else if (Conversion.ToString(dt.Rows[i]["ActivityType"]) == "DestinationPort")
				{
					dtDestinationPort.Rows.Add(dt.Rows[i]["Id"], dt.Rows[i]["name"]);
				}
				else if (Conversion.ToString(dt.Rows[i]["ActivityType"]) == "Items")
				{
					dtItem.Rows.Add(dt.Rows[i]["Id"], dt.Rows[i]["name"]);
				}
			}
			if (dtCustomer.Rows.Count > 0)
			{
				DDL.BindDDL(dtCustomer, CmbSupplier, "Id", "CustomerName", "Customer Name", ZeroIndex: false);
			}
			else
			{
				((UltraGridBase)CmbSupplier).DataSource = null;
			}
			if (dtInvoice.Rows.Count > 0)
			{
				DDL.BindDDL(dtInvoice, cmbInvoiceNo, "Id", "Invoice", "Invoice No", ZeroIndex: false);
			}
			else
			{
				((UltraGridBase)cmbInvoiceNo).DataSource = null;
			}
			if (dtLoadingPort.Rows.Count > 0)
			{
				DDL.BindDDL(dtLoadingPort, cmbLoadingPort, "Id", "Port", "Loading Port", ZeroIndex: false);
			}
			else
			{
				((UltraGridBase)cmbLoadingPort).DataSource = null;
			}
			if (dtDestinationPort.Rows.Count > 0)
			{
				DDL.BindDDL(dtDestinationPort, CmbDestinationPort, "Id", "Port", "Destination Port", ZeroIndex: false);
			}
			else
			{
				((UltraGridBase)CmbDestinationPort).DataSource = null;
			}
			if (dtItem.Rows.Count > 0)
			{
				DDL.BindDDL(dtItem, CmbServiceItem, "Id", "ItemName", "Service Item's", ZeroIndex: false);
			}
			else
			{
				((UltraGridBase)CmbDestinationPort).DataSource = null;
