	private void btnLoadOnInvoice_Click_1(object sender, EventArgs e)
	{
		try
		{
			dtForLoad = dtgrid.Clone();
			if (int.Parse(grd.GetCheckedRows().Count().ToString()) > 0)
			{
				int OrderSupCustId = 0;
				int BillCalculateTypeId = 0;
				dtForLoad.Rows.Clear();
				GridEXRow[] checkedRows = grd.GetCheckedRows();
				foreach (GridEXRow r in checkedRows)
				{
					int Id = Conversion.ToInt(r.Cells["OrderSupCustId"].Value);
					int BillTypeId = Conversion.ToInt(r.Cells["BillCalculateTypeId"].Value);
					if (OrderSupCustId == 0)
					{
						OrderSupCustId = Id;
					}
					if (BillCalculateTypeId == 0)
					{
						BillCalculateTypeId = BillTypeId;
					}
					if (OrderSupCustId != Id || BillCalculateTypeId != BillTypeId)
					{
						dtForLoad.Rows.Clear();
						MessageBox.Show("You Can Only Select Rows Of Same Supplier and Bill Type");
						return;
					}
					DataRow dr = dtgrid.Rows[r.RowIndex];
					dtForLoad.Rows.Add(dr.ItemArray);
				}
				Hide();
			}
			else
			{
				MessageBox.Show("Check the Row first");
			}
		}
		catch (Exception ex)
		{
			MessageBox.Show(ex.Message);
		}
	}

