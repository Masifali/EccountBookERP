	private void BtnLoad(object sender, EventArgs e)
	{
		try
		{
			string Ids = "";
			GridEXRow[] checkedRows = grd.GetCheckedRows();
			if (checkedRows.Length != 0)
			{
				int SupplierCustomerId = 0;
				GridEXRow[] array = checkedRows;
				foreach (GridEXRow row in array)
				{
					int currentSupplierCustomerId = Conversion.ToInt(row.Cells["SupplierCustomerId"].Value);
					if (SupplierCustomerId == 0)
					{
						SupplierCustomerId = currentSupplierCustomerId;
					}
					if (SupplierCustomerId != currentSupplierCustomerId)
					{
						Ids = "";
						MessageBox.Show("Sorry! The selected Row's are not of the same SupplierCustomerI.");
						return;
					}
					Ids = Ids + "," + row.Cells["Id"].Value.ToString();
					SupplierCustomerId = currentSupplierCustomerId;
				}
				if (Ids != string.Empty)
				{
					string[] idsArray = Ids.Split(',');
					EnumerableRowCollection<DataRow> rows = from r in dtGrid.AsEnumerable()
						where idsArray.Contains(r.Field<int>("Id").ToString())
						select r;
					dtLoader = (rows.Any() ? rows.CopyToDataTable() : dtGrid.Clone());
				}
				Hide();
				return;
			}
			throw new Exception("Check the row first");
		}
		catch (Exception ex)
		{
			MessageBox.Show(ex.Message, "Error Message", MessageBoxButtons.OK, MessageBoxIcon.Hand);
		}
	}

